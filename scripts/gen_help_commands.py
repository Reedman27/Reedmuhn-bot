"""Regenerate webui/help_commands.py from the slash commands defined in cogs/.

The dashboard runs in its own container and never imports the cogs, so the
Wiki pages read a generated snapshot of every slash command instead. The cogs
are parsed with ``ast`` (never imported or executed).

    python scripts/gen_help_commands.py           # rewrite webui/help_commands.py
    python scripts/gen_help_commands.py --check   # exit 1 if it is out of date

tests/test_help_commands_in_sync.py runs the --check form, so adding or
renaming a command without regenerating fails the test suite.
"""
from __future__ import annotations

import ast
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "webui" / "help_commands.py"

PERMISSION_LABELS = {
    "manage_guild": "Manage Server",
    "moderate_members": "Moderate Members",
    "manage_roles": "Manage Roles",
    "manage_channels": "Manage Channels",
    "manage_messages": "Manage Messages",
    "manage_nicknames": "Manage Nicknames",
    "ban_members": "Ban Members",
    "kick_members": "Kick Members",
}

HEADER = '''"""Slash commands for the dashboard Wiki pages.

GENERATED by scripts/gen_help_commands.py from cogs/ - do not edit by hand.
Each entry is (command, description, requirement). The requirement is empty
when the command has no Discord-permission gate of its own.
"""

COMMANDS = '''


def _kw(call: ast.Call, name: str):
    for keyword in call.keywords:
        if keyword.arg == name:
            return keyword.value
    return None


def _const(node):
    return node.value if isinstance(node, ast.Constant) else None


def _decorator_name(call: ast.Call) -> str:
    if isinstance(call.func, ast.Name):
        return call.func.id
    if isinstance(call.func, ast.Attribute):
        return call.func.attr
    return ""


def _requirement(decorators: list[ast.expr]) -> str:
    for dec in decorators:
        if not isinstance(dec, ast.Call):
            continue
        name = _decorator_name(dec)
        if name == "manager_or_permission" and dec.args:
            label = PERMISSION_LABELS.get(_const(dec.args[0]), str(_const(dec.args[0])))
            return f"{label} (or Administrator, or a Bot Manager role)"
        if name == "has_permissions":
            labels = [PERMISSION_LABELS.get(k.arg, k.arg) for k in dec.keywords if k.arg]
            if labels:
                return f"{', '.join(labels)} (or Administrator; Bot Manager roles do not apply)"
        if name == "owner_or_administrator":
            return "Server owner or Administrator"
    return ""


def collect(root: Path = ROOT) -> dict[str, list[tuple[str, str, str]]]:
    """Top-level command name -> [(qualified command, description, requirement)]."""
    found: dict[str, list[tuple[str, str, str]]] = {}
    for path in sorted((root / "cogs").glob("*/*.py")):
        if path.name.startswith("_"):
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for cls in (n for n in tree.body if isinstance(n, ast.ClassDef)):
            groups: dict[str, str] = {}
            for node in cls.body:
                if (
                    isinstance(node, ast.Assign)
                    and isinstance(node.value, ast.Call)
                    and isinstance(node.value.func, ast.Attribute)
                    and node.value.func.attr == "Group"
                    and isinstance(node.targets[0], ast.Name)
                ):
                    name = _const(_kw(node.value, "name"))
                    parent = _kw(node.value, "parent")
                    if isinstance(parent, ast.Name) and parent.id in groups:
                        name = f"{groups[parent.id]} {name}"
                    groups[node.targets[0].id] = name
            for node in cls.body:
                if not isinstance(node, (ast.AsyncFunctionDef, ast.FunctionDef)):
                    continue
                for dec in node.decorator_list:
                    if not (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute) and dec.func.attr == "command"):
                        continue
                    owner = dec.func.value
                    name = _const(_kw(dec, "name")) or node.name
                    description = _const(_kw(dec, "description")) or ""
                    if isinstance(owner, ast.Name) and owner.id in groups:
                        qualified = f"{groups[owner.id]} {name}"
                    elif (isinstance(owner, ast.Name) and owner.id == "app_commands") or (
                        isinstance(owner, ast.Attribute) and owner.attr == "app_commands"
                    ):
                        qualified = name
                    else:
                        continue
                    found.setdefault(qualified.split()[0], []).append(
                        (qualified, description, _requirement(node.decorator_list))
                    )
    return found


def render(root: Path = ROOT) -> str:
    return HEADER + pprint.pformat(collect(root), width=110, sort_dicts=False) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("webui/help_commands.py is out of date - run: python scripts/gen_help_commands.py")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
